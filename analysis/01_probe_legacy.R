suppressPackageStartupMessages(library(Seurat))
args <- commandArgs(trailingOnly=TRUE)
o <- readRDS(args[1])
cat('cells=',ncol(o), ' genes=',nrow(o),'\n')
cat('Meta:', paste(colnames(o[[]]), collapse=', '), '\n')
if ('sample' %in% names(o[[]])) print(table(o$sample))
if ('group' %in% names(o[[]])) print(table(o$group))
print(names(o@commands))
saveRDS(o[[]],file.path(args[2], 'main_legacy_minimal_metadata.rds'))
write.csv(o[[]],file.path(args[2], 'main_legacy_minimal_metadata.csv'))
print(sessionInfo())
